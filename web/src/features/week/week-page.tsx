import { useMutation, useQuery, useQueryClient } from '@tanstack/react-query'
import { Link } from '@tanstack/react-router'
import { useEffect, useMemo, useRef, useState } from 'react'
import {
  addRecipe,
  ApiRequestError,
  closeCurrentWeek,
  generateWeek,
  randomSwapRecipe,
  removeRecipe,
  swapRecipe,
  type RecipeSummary,
  type Week,
  type WeekHistorySummary,
} from '../../api/client'
import { ArrowIcon, CloseIcon, PlusIcon, SwapIcon, TrashIcon } from '../../ui/icons'
import { historyQueryKey, historyQueryOptions } from '../history/queries'
import { settingsQueryOptions } from '../settings/queries'
import { deviceToday, formatWeekRange, formatShortDate } from './dates'
import { currentWeekQueryOptions, recipesQueryOptions, weekQueryKey } from './queries'

const groceriesQueryKey = ['week', 'groceries'] as const

type WeekAction =
  | { type: 'generate'; recipeCount: number }
  | { type: 'add'; recipeId: number }
  | { type: 'remove'; occurrenceId: number }
  | { type: 'random-swap'; occurrenceId: number }
  | { type: 'swap'; occurrenceId: number; recipeId: number }

type PickerState = { mode: 'add' } | { mode: 'swap'; occurrenceId: number }

export function WeekPage() {
  const queryClient = useQueryClient()
  const weekQuery = useQuery(currentWeekQueryOptions)
  const recipesQuery = useQuery(recipesQueryOptions)
  const settingsQuery = useQuery(settingsQueryOptions)
  // The plan closed from this page. Until a new plan is generated it is the plan the "Start a new
  // plan" step links to, so that step never waits on, or is hidden by, a failed reload.
  const [closedWeek, setClosedWeek] = useState<WeekHistorySummary | null>(null)
  // A plan closed here is never shown again, even before a reload confirms that it closed.
  const week = weekQuery.data && weekQuery.data.id === closedWeek?.id ? null : weekQuery.data
  // With no current plan, the plan that most recently ended decides between a first-time start
  // and "Start a new plan". It is only needed then.
  const historyQuery = useQuery({ ...historyQueryOptions, enabled: week === null })
  // null until someone picks a count here; until then the household's default applies.
  const [recipeCount, setRecipeCount] = useState<number | null>(null)
  const [picker, setPicker] = useState<PickerState | null>(null)
  const [confirmingClose, setConfirmingClose] = useState(false)
  // Set when the user starts a new plan, so the count control takes focus once it appears.
  const [focusCount, setFocusCount] = useState(false)
  const startNextButton = useRef<HTMLButtonElement>(null)
  const countSelect = useRef<HTMLSelectElement>(null)

  const mutation = useMutation({
    mutationKey: ['week'],
    mutationFn: runWeekAction,
    onSuccess: (week) => {
      queryClient.setQueryData(weekQueryKey, week)
      setClosedWeek(null)
      setPicker(null)
    },
  })

  const closeMutation = useMutation({
    mutationKey: ['week', 'close'],
    mutationFn: closeWeek,
    onSuccess: async (_, closing) => {
      void queryClient.invalidateQueries({ queryKey: groceriesQueryKey })
      // The History entry for the plan just closed, if History can be reloaded now.
      let ended: WeekHistorySummary | undefined
      try {
        // Planning never waits long on History: after a short wait the fallback below is shown,
        // and the History list replaces it once it loads.
        const history = queryClient.fetchQuery({ ...historyQueryOptions, staleTime: 0 })
        ended = (await Promise.race([history, timeout(historyWaitMs)])).weeks[0]
      } catch {
        void queryClient.invalidateQueries({ queryKey: historyQueryKey })
      }
      setClosedWeek(ended?.id === closing.id ? ended : {
        id: closing.id, startsOn: closing.startsOn, endsOn: max(deviceToday(), closing.startsOn), recipeCount: closing.recipes.length, groceryCount: 0, completedCount: 0,
      })
      setFocusCount(true)
      setConfirmingClose(false)
      queryClient.setQueryData(weekQueryKey, null)
      void queryClient.invalidateQueries({ queryKey: weekQueryKey })
    },
  })

  const recipes = recipesQuery.data?.recipes ?? []
  const maxCount = Math.max(1, recipes.length)
  // Settings never block the page: if they fail to load, 5 is offered. While they load, the count
  // cannot be chosen or submitted, so a stand-in value is never generated by mistake.
  const settingsPending = recipeCount === null && settingsQuery.isPending
  const selectedCount = Math.min(recipeCount ?? settingsQuery.data?.defaultRecipeCount ?? 5, maxCount)
  // History never blocks planning: if it fails to load, the first-time start is shown. After a
  // close here the plan that ended is already known.
  const isLoading = weekQuery.isLoading || recipesQuery.isLoading || (week === null && closedWeek === null && historyQuery.isLoading)
  // Right after a close, a failed reload of the current plan must not hide the next step.
  const readError = (week === null && closedWeek !== null ? null : weekQuery.error) ?? recipesQuery.error

  // The user asked for this transition, so the recipe count takes focus once it can.
  const countReady = !isLoading && !readError && week === null && !settingsPending
  useEffect(() => {
    if (!focusCount || !countReady || !countSelect.current) return
    countSelect.current.focus({ preventScroll: true })
    countSelect.current.scrollIntoView({ block: 'center' })
    setFocusCount(false)
  }, [focusCount, countReady])

  // Cancelling the confirmation returns focus to the button that opened it. After a close that
  // button is gone and the recipe count takes focus instead.
  const wasConfirming = useRef(false)
  useEffect(() => {
    if (wasConfirming.current && !confirmingClose) startNextButton.current?.focus()
    wasConfirming.current = confirmingClose
  }, [confirmingClose])

  if (isLoading) return <WeekSkeleton />
  if (readError) {
    return <ErrorPanel message={readError.message} onRetry={() => void queryClient.invalidateQueries()} />
  }

  if (!week) {
    const generate = (
      <GenerateControls
        count={selectedCount}
        maxCount={maxCount}
        countPending={settingsPending}
        canGenerate={recipes.length > 0}
        pending={mutation.isPending}
        error={mutation.error}
        onCountChange={setRecipeCount}
        onGenerate={() => mutation.mutate({ type: 'generate', recipeCount: selectedCount })}
        selectRef={countSelect}
      />
    )
    // History, once it holds the plan closed here, is the better record of it than the fallback.
    const latest = historyQuery.data?.weeks?.[0]
    const lastPlan = closedWeek && latest?.id !== closedWeek.id ? closedWeek : latest
    if (lastPlan) {
      return (
        <section aria-labelledby="week-heading">
          <PageHeading count={0} week={null} />
          <StartNewPlan lastPlan={lastPlan}>{generate}</StartNewPlan>
        </section>
      )
    }
    return (
      <section aria-labelledby="week-heading">
        <PageHeading count={0} week={null} />
        <div className="empty-week">
          <div className="empty-mark" aria-hidden="true">✦</div>
          <h2 id="week-heading">Build your first plan</h2>
          <p>Pick meals for as long as you like, until your next shopping trip. You can add, remove, or swap any recipe afterward.</p>
          {generate}
        </div>
      </section>
    )
  }

  return (
    <section aria-labelledby="week-heading" aria-busy={mutation.isPending}>
      <PageHeading count={week.recipes.length} week={week}>
        <button className="button" type="button" onClick={() => mutation.mutate({ type: 'generate', recipeCount: week.recipes.length })} disabled={mutation.isPending || week.recipes.length === 0}>
          <SwapIcon /> Refresh pool
        </button>
        <button className="button primary" type="button" onClick={() => setPicker({ mode: 'add' })} disabled={mutation.isPending}>
          <PlusIcon /> Add recipe
        </button>
      </PageHeading>

      <div className="recipe-list">
        {week.recipes.map((occurrence) => (
          <article className="recipe-row" key={occurrence.id}>
            <div className="recipe-grip" aria-hidden="true">⠿</div>
            <div className="recipe-main">
              <h2>{occurrence.recipe.name}</h2>
              <div className="recipe-meta">
                {durationLabel(occurrence.recipe) && <span>{durationLabel(occurrence.recipe)}</span>}
                {occurrence.recipe.yield && <span>{occurrence.recipe.yield}</span>}
              </div>
            </div>
            <div className="recipe-pills">
              {durationLabel(occurrence.recipe) && <span className="pill">{durationLabel(occurrence.recipe)}</span>}
              {occurrence.recipe.yield && <span className="pill">{occurrence.recipe.yield}</span>}
            </div>
            <div className="recipe-actions">
              <Link className="icon-button detail-action" to="/recipes/$recipeId" params={{ recipeId: String(occurrence.recipe.id) }} aria-label={`Open ${occurrence.recipe.name}`}>
                <ArrowIcon />
              </Link>
              <button className="icon-button" type="button" onClick={() => mutation.mutate({ type: 'random-swap', occurrenceId: occurrence.id })} disabled={mutation.isPending} aria-label={`Randomly swap ${occurrence.recipe.name}`} title="Random swap">
                <SwapIcon />
              </button>
              <button className="icon-button specific-swap" type="button" onClick={() => setPicker({ mode: 'swap', occurrenceId: occurrence.id })} disabled={mutation.isPending} aria-label={`Choose a replacement for ${occurrence.recipe.name}`} title="Choose replacement">
                <span aria-hidden="true">•••</span>
              </button>
              <button className="icon-button danger" type="button" onClick={() => mutation.mutate({ type: 'remove', occurrenceId: occurrence.id })} disabled={mutation.isPending} aria-label={`Remove ${occurrence.recipe.name}`} title="Remove">
                <TrashIcon />
              </button>
            </div>
          </article>
        ))}
      </div>

      <div className="week-footer">
        <span>Started {formatShortDate(week.startsOn)}</span>
        <span>{week.recipes.length} {week.recipes.length === 1 ? 'recipe' : 'recipes'}</span>
      </div>
      <MutationError error={mutation.error} />
      {!confirmingClose && <MutationError error={closeMutation.error} />}
      <div className="week-close">
        <button ref={startNextButton} className="button" type="button" onClick={() => { closeMutation.reset(); setConfirmingClose(true) }} disabled={mutation.isPending}>
          Start new plan
        </button>
      </div>

      {confirmingClose && (
        <ConfirmStartNewPlan
          pending={closeMutation.isPending}
          error={closeMutation.error}
          onCancel={() => setConfirmingClose(false)}
          onConfirm={() => closeMutation.mutate(week)}
        />
      )}

      {picker && (
        <RecipePicker
          key={`${picker.mode}-${picker.mode === 'swap' ? picker.occurrenceId : 'new'}`}
          picker={picker}
          recipes={recipes}
          pending={mutation.isPending}
          onClose={() => setPicker(null)}
          onChoose={(recipeId) => {
            if (picker.mode === 'add') mutation.mutate({ type: 'add', recipeId })
            else mutation.mutate({ type: 'swap', occurrenceId: picker.occurrenceId, recipeId })
          }}
        />
      )}
    </section>
  )
}

function PageHeading({ count, week, children }: { count: number; week: Week | null; children?: React.ReactNode }) {
  return (
    <header className="page-heading">
      <div>
        <div className="eyebrow">Until your next trip</div>
        <div className="week-title-line">
          <h1 id="week-heading">Current plan</h1>
          <span className={`planning-status ${week ? 'planned' : 'unplanned'}`}>{week ? `Planned · ${count} ${count === 1 ? 'meal' : 'meals'}` : 'Not planned'}</span>
        </div>
        <p>{week ? formatWeekRange(week.startsOn, week.endsOn) : 'Choose your meals when you’re ready.'}</p>
      </div>
      <div className="page-actions">{children}</div>
      <span className="page-count">{count} {count === 1 ? 'recipe' : 'recipes'}</span>
    </header>
  )
}

// GenerateControls is the recipe-count control and the Generate button that start a plan.
function GenerateControls({
  count,
  maxCount,
  countPending,
  canGenerate,
  pending,
  error,
  onCountChange,
  onGenerate,
  selectRef,
}: {
  count: number
  maxCount: number
  countPending: boolean
  canGenerate: boolean
  pending: boolean
  error: Error | null
  onCountChange: (count: number) => void
  onGenerate: () => void
  selectRef?: React.Ref<HTMLSelectElement>
}) {
  return (
    <>
      <label className="count-field">
        Recipes
        <select ref={selectRef} value={count} onChange={(event) => onCountChange(Number(event.target.value))} disabled={pending || countPending}>
          {Array.from({ length: maxCount }, (_, index) => index + 1).map((value) => (
            <option key={value} value={value}>{value}</option>
          ))}
        </select>
      </label>
      <button className="button primary" type="button" disabled={pending || countPending || !canGenerate} onClick={onGenerate}>
        {pending ? 'Generating…' : 'Generate plan'}
      </button>
      <MutationError error={error} />
    </>
  )
}

// StartNewPlan follows a closed plan: the next one starts only when someone presses Generate. It
// links to the plan that ended, which can be reopened from History, and offers the generate
// control directly.
function StartNewPlan({ lastPlan, children }: { lastPlan: WeekHistorySummary; children: React.ReactNode }) {
  return (
    <div className="empty-week plan-next-week">
      <div className="empty-mark" aria-hidden="true">✦</div>
      <h2>Start a new plan</h2>
      <p>
        Your plan for {formatWeekRange(lastPlan.startsOn, lastPlan.endsOn)} is in History.{' '}
        <Link to="/history/$weekId" params={{ weekId: String(lastPlan.id) }}>View or reopen it</Link>
      </p>
      {children}
    </div>
  )
}

// ConfirmStartNewPlan asks before the plan is closed. Closing only ends this plan; the next one
// exists once someone presses Generate.
function ConfirmStartNewPlan({ pending, error, onCancel, onConfirm }: {
  pending: boolean
  error: Error | null
  onCancel: () => void
  onConfirm: () => void
}) {
  const dialog = useRef<HTMLDialogElement>(null)
  useEffect(() => { const element = dialog.current; element?.showModal(); return () => element?.close() }, [])
  return (
    <dialog ref={dialog} className="picker-dialog confirm-dialog" aria-labelledby="start-next-title" aria-describedby="start-next-description"
      onCancel={(event) => { event.preventDefault(); if (!pending) onCancel() }}
      // However the dialog is closed, the page follows; a close still running reports its error on
      // the page instead. The close event is queued, so one from a close() the page has since
      // undone by reopening (as React's development double mount does) is ignored.
      onClose={(event) => { if (!event.currentTarget.open) onCancel() }}>
      <header>
        <div><div className="eyebrow">Current plan</div><h2 id="start-next-title">Start a new plan</h2></div>
      </header>
      <p className="dialog-note" id="start-next-description">This plan’s meals and grocery list move to History, where you can reopen it later. Unchecked items stay unchecked.</p>
      {error && <p className="inline-error dialog-error" role="alert">{error.message}</p>}
      <footer>
        <button className="button" type="button" onClick={onCancel} disabled={pending}>Cancel</button>
        <button className="button primary" type="button" onClick={onConfirm} disabled={pending}>
          {pending ? 'Closing…' : 'Close plan and start a new one'}
        </button>
      </footer>
    </dialog>
  )
}

function RecipePicker({
  picker,
  recipes,
  pending,
  onClose,
  onChoose,
}: {
  picker: PickerState
  recipes: RecipeSummary[]
  pending: boolean
  onClose: () => void
  onChoose: (recipeId: number) => void
}) {
  const sortedRecipes = useMemo(() => [...recipes].sort((a, b) => a.name.localeCompare(b.name)), [recipes])
  const [recipeId, setRecipeId] = useState(sortedRecipes[0]?.id ?? 0)
  const title = picker.mode === 'add' ? 'Add a recipe' : 'Choose a replacement'

  return (
    <div className="dialog-layer" onMouseDown={(event) => event.target === event.currentTarget && onClose()}>
      <dialog className="picker-dialog" open aria-labelledby="picker-title">
        <header>
          <div><div className="eyebrow">Recipe pool</div><h2 id="picker-title">{title}</h2></div>
          <button className="icon-button" type="button" onClick={onClose} aria-label="Close"><CloseIcon /></button>
        </header>
        <label>
          Recipe
          <select value={recipeId} onChange={(event) => setRecipeId(Number(event.target.value))} autoFocus>
            {sortedRecipes.map((recipe) => <option key={recipe.id} value={recipe.id}>{recipe.name}</option>)}
          </select>
        </label>
        <footer>
          <button className="button" type="button" onClick={onClose}>Cancel</button>
          <button className="button primary" type="button" disabled={pending || recipeId === 0} onClick={() => onChoose(recipeId)}>
            {pending ? 'Saving…' : picker.mode === 'add' ? 'Add recipe' : 'Replace recipe'}
          </button>
        </footer>
      </dialog>
    </div>
  )
}

function WeekSkeleton() {
  return (
    <section aria-label="Loading your plan" aria-busy="true">
      <PageHeading count={0} week={null} />
      <div className="recipe-list skeleton-list">
        {Array.from({ length: 4 }, (_, index) => <div className="skeleton-row" key={index} />)}
      </div>
    </section>
  )
}

function ErrorPanel({ message, onRetry }: { message: string; onRetry: () => void }) {
  return (
    <div className="error-panel" role="alert">
      <div><strong>Couldn’t load your plan.</strong><p>{message}</p></div>
      <button className="button" type="button" onClick={onRetry}>Try again</button>
    </div>
  )
}

function MutationError({ error }: { error: Error | null }) {
  if (!error) return null
  return <p className="inline-error" role="alert">{error.message}</p>
}

function durationLabel(recipe: RecipeSummary): string | null {
  const minimum = recipe.handsOn.minimumMinutes
  const maximum = recipe.handsOn.maximumMinutes
  if (minimum === null && maximum === null) return null
  if (minimum === maximum || maximum === null) return `${minimum} min hands-on`
  if (minimum === null) return `Up to ${maximum} min hands-on`
  return `${minimum}–${maximum} min hands-on`
}

// historyWaitMs bounds how long a close waits for History before showing the next step.
const historyWaitMs = 2500

function timeout(ms: number): Promise<never> {
  return new Promise((_, reject) => setTimeout(() => reject(new Error('timed out')), ms))
}

function max(first: string, second: string): string {
  return first > second ? first : second
}

// closeWeek closes the plan shown. If another member had already closed it, the outcome is the
// same: there is no current plan and the next one can be generated.
async function closeWeek(_closing: Week): Promise<void> {
  try {
    await closeCurrentWeek()
  } catch (error) {
    if (error instanceof ApiRequestError && error.code === 'no_current_week') return
    throw error
  }
}

function runWeekAction(action: WeekAction): Promise<Week> {
  switch (action.type) {
    case 'generate': return generateWeek(action.recipeCount)
    case 'add': return addRecipe(action.recipeId)
    case 'remove': return removeRecipe(action.occurrenceId)
    case 'random-swap': return randomSwapRecipe(action.occurrenceId)
    case 'swap': return swapRecipe(action.occurrenceId, action.recipeId)
  }
}
